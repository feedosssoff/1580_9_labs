"""
АЛГОРИТМ:

1. Начало программы

2. Получить данные от пользователя:
   - Запросить ввод времени через пробел
   - Убрать лишние пробелы

3. Проверка корректности вводных данных:
   а) Если введена пустая строка:
      - Вывести ошибку "Ошибка: ничего не было введено"
      - Завершить программу

   б) Разделить строку по пробелам
   в) Если количество частей не равно 2:
      - Вывести ошибку "Ошибка: требуется 2 целых числа через пробел"
      - Завершить программу

   г) Проверить часы и минуты на содержание только цифр:
      - Если часы содержат не только цифры ИЛИ минуты содержат не только цифры:
        - Вывести ошибку "Ошибка: некорректные символы. Введите 2 целых числа через пробел"
        - Завершить программу

   д) Преобразовать часы и минуты в целые числа

4. Проверить допустимость значений:
   а) Если часы < 0 ИЛИ часы > 23:
      - Вывести ошибку "Введены недопустимые данные: часы должны быть от 0 до 23"
      - Завершить программу

   б) Если минуты < 0 ИЛИ минуты > 59:
      - Вывести ошибку "Введены недопустимые данные: минуты должны быть от 0 до 59"
      - Завершить программу

5. Определить время суток:
   - Если часы от 6 до 11 -> "утра"
   - Если часы от 12 до 17 -> "дня"
   - Если часы от 18 до 23 -> "вечера"
   - Если часы от 0 до 5 -> "ночи"
   - Вернуть время суток

6. Преобразовать часы в нужную форму:
   а) Преобразовать часы в 12-часовой формат:
      - Если часы = 0 -> часы = 12
      - Если часы > 12 -> часы = часы - 12

   б) Определить склонение:
      - Если последняя цифра часов = 1 И часы ≠ 11 -> "часы час"
      - Если последняя цифра часов от 2 до 4 И первые цифры не 1 -> "часы часа"
      - Иначе -> "часы часов"
   в) Вернуть результат

7. Преобразовать минуты в нужную форму:
   а) Определить склонение:
      - Если последняя цифра минут = 1 И минуты ≠ 11 -> "минуты минута"
      - Если последняя цифра минут от 2 до 4 И первые цифры не 1 -> "минуты минуты"
      - Иначе -> "минуты минут"
   б) Вернуть результат

8. Составление итогового результата:
   а) Проверить особые случаи:
      - Если часы = 0 И минуты = 0 -> вернуть "полночь"
      - Если часы = 12 И минуты = 0 -> вернуть "полдень"

   б) Получить время суток
   в) Получить часы в 12-часовом формате с падежом
   г) Если минуты = 0:
        результат = часы с падежом + " " + время суток + " ровно"
      Иначе:
        результат = часы с падежом + " " + минуты с падежом + " " + время суток
   д) Вернуть результат

9. Вывести результат
10. Конец программы
"""

def get_day_period(hours):
    if hours >= 6 and hours < 12:
        return "утра"
    elif hours >= 12 and hours < 18:
        return "дня"
    elif hours >= 18 and hours < 24:
        return "вечера"
    elif hours >= 0 and hours < 6:
        return "ночи"

def hour_declination(hours):
    if hours % 10 == 1 and hours != 11:
        return str(hours) + " час"
    elif (hours % 10 >= 2 and hours % 10 <= 4) and not (hours//10 == 1):
        return str(hours) + " часа"
    else:
        return str(hours) + " часов"

def minute_declination(minutes):
    if minutes % 10 == 1 and minutes != 11:
        return str(minutes) + " минута"
    elif (minutes % 10 >= 2 and minutes % 10 <= 4) and not (minutes//10 == 1):
        return str(minutes) + " минуты"
    else:
        return str(minutes) + " минут"

def correct_number(number):
    return number.isdigit()

def get_time_in_words(hours, minutes):
    if hours == 0 and minutes == 0:
        return "полночь"
    if hours == 12 and minutes == 0:
        return "полдень"

    period = get_day_period(hours)

    hours_in_12 = hours
    if hours == 0:
        hours_in_12 = 12
    elif hours > 12:
        hours_in_12 = hours - 12

    hours_in_12_in_words = hour_declination(hours_in_12)
    
    if minutes == 0:
        result = hours_in_12_in_words + " " + period + " ровно"
    else:
        minutes_in_words = minute_declination(minutes)
        result = hours_in_12_in_words + " " + minutes_in_words + " " + period

    return result

def main():
    data_input = input("Введите время через пробел: ").strip()
    if not data_input:
        print("Ошибка: ничего не было введено.")
        return

    data_parts = data_input.split()
    if len(data_parts) != 2:
        print("Ошибка: требуется 2 целых числа через пробел.")
        return

    hours, minutes = data_parts

    if not (correct_number(hours) and correct_number(minutes)):
        print("Ошибка: некорректные символы. Введите 2 целых числа через пробел.")
        return

    hours, minutes = int(hours), int(minutes)

    if hours < 0 or hours > 23:
        print("Введены недопустимые данные: часы должны быть от 0 до 23.")
        return

    if minutes < 0 or minutes > 59:
        print("Введены недопустимые данные: минуты должны быть от 0 до 59.")
        return

    print(get_time_in_words(hours, minutes))

if __name__ == "__main__":
    main()
