import random

def selection_sort(arr):
    comparisons = 0
    swaps = 0
    length = len(arr)
    
    for i in range(length-1):
        min_index = i
        for j in range(i+1, length):
            comparisons += 1
            if arr[j] < arr[min_index]:
                min_index = j
        
        if min_index != i:
            arr[i], arr[min_index] = arr[min_index], arr[i]
            swaps += 1
    
    return comparisons, swaps

def bubble_sort(arr):
    comparisons = 0
    swaps = 0
    length = len(arr)
    
    for i in range(length-1):
        swapped = False
        for j in range(length-i-1):
            comparisons += 1
            if arr[j] > arr[j+1]:
                arr[j], arr[j+1] = arr[j+1], arr[j]
                swaps += 1
                swapped = True
        
        if not swapped:
            break
    
    return comparisons, swaps

def insertion_sort(arr):
    comparisons = 0
    swaps = 0
    length = len(arr)
    
    for i in range(1, length):
        value = arr[i]
        j = i-1
        
        while j >= 0:
            comparisons += 1
            if arr[j] > value:
                arr[j+1] = arr[j]
                swaps += 1
                j -= 1
            else:
                break
        
        arr[j+1] = value
    
    return comparisons, swaps

def is_int(s):
    s = s.strip()
    if not s:
        return False
    if s[0] == '-':
        return s[1:].isdigit() if len(s) > 1 else False
    return s.isdigit()

